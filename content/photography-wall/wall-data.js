export function pickColumns(width) {
  if (width >= 1600) return 8;
  if (width >= 1300) return 7;
  if (width >= 1000) return 6;
  if (width >= 720) return 5;
  if (width >= 520) return 4;
  return 3;
}

export function columnFactor(index, variance = .5) {
  const pseudo = ((index * .6180339887 + .35) % 1) * 2 - 1;
  return 1 + variance * pseudo;
}

export function layoutColumns(items, count, tileWidth, gap, viewportHeight) {
  const columns = Array.from({ length: count }, () => []);
  items.forEach((photo, index) => columns[index % count].push(photo));
  return columns.map(column => {
    const entries = column.map(photo => ({ photo, height: tileWidth * (photo.originalHeight || photo.height) / (photo.originalWidth || photo.width) }));
    // Every tile includes its gap, including the final tile. This is the exact wrapping period.
    const repeatHeight = entries.reduce((sum, item) => sum + item.height + gap, 0);
    return { items: entries, repeatHeight, copies: Math.max(2, Math.ceil(viewportHeight * 1.8 / repeatHeight) + 1) };
  });
}

